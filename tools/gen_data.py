#!/usr/bin/env python3
"""Generates language files, models, blockstates, recipes, loot tables, tags and DialogLines.java.
Run from the repository root: python3 tools/gen_data.py"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from lang_ui import UI  # noqa: E402
from lang_dialogs import D  # noqa: E402

RES = os.path.join("src", "main", "resources")
ASSETS = os.path.join(RES, "assets", "imperium")
DATA = os.path.join(RES, "data")
MOD = "imperium"


def write(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        if isinstance(obj, str):
            f.write(obj)
        else:
            json.dump(obj, f, ensure_ascii=False, indent=2)
            f.write("\n")


# ---------------------------------------------------------------- lang
def gen_lang():
    en, pl = {}, {}
    for k, (e, p) in UI.items():
        en[k] = e
        pl[k] = p
    for base, lines in D.items():
        for i, (e, p) in enumerate(lines):
            en["imperium.dlg.%s.%d" % (base, i)] = e
            pl["imperium.dlg.%s.%d" % (base, i)] = p
    write(os.path.join(ASSETS, "lang", "en_us.json"), dict(sorted(en.items())))
    write(os.path.join(ASSETS, "lang", "pl_pl.json"), dict(sorted(pl.items())))
    # DialogLines.java
    lines = []
    for base, items in sorted(D.items()):
        lines.append('        COUNTS.put("imperium.dlg.%s", %d);' % (base, len(items)))
    java = """package com.endruqq.imperium.game;

import java.util.HashMap;
import java.util.Map;

/** Number of variants for every dialog line key. GENERATED by tools/gen_data.py - do not edit by hand. */
public final class DialogLines {
    private static final Map<String, Integer> COUNTS = new HashMap<>();

    static {
%s
    }

    private DialogLines() {}

    public static int count(String key) {
        return COUNTS.getOrDefault(key, 0);
    }
}
""" % "\n".join(lines)
    write(os.path.join("src", "main", "java", "com", "endruqq", "imperium", "game", "DialogLines.java"), java)
    return en


# ---------------------------------------------------------------- models
def block_model(name, parent, textures):
    write(os.path.join(ASSETS, "models", "block", name + ".json"), {"parent": parent, "textures": textures})


def item_model(name, parent=None, layer=None):
    if layer:
        obj = {"parent": parent or "minecraft:item/generated", "textures": {"layer0": layer}}
    else:
        obj = {"parent": parent}
    write(os.path.join(ASSETS, "models", "item", name + ".json"), obj)


def gen_models():
    b = MOD + ":block/"
    block_model("province_core", "minecraft:block/cube_all", {"all": b + "province_core"})
    block_model("construction_site", "minecraft:block/cube_all", {"all": b + "construction_site"})
    block_model("construction_site_active", "minecraft:block/cube_all", {"all": b + "construction_site_active"})
    block_model("treasury", "minecraft:block/cube_bottom_top", {"top": b + "treasury_top", "bottom": b + "treasury_top", "side": b + "treasury_side"})
    block_model("steel_block", "minecraft:block/cube_all", {"all": b + "steel_block"})
    block_model("steel_furnace", "minecraft:block/orientable", {"top": b + "steel_furnace_top", "front": b + "steel_furnace_front", "side": b + "steel_furnace_side"})
    block_model("steel_furnace_on", "minecraft:block/orientable", {"top": b + "steel_furnace_top", "front": b + "steel_furnace_front_on", "side": b + "steel_furnace_side"})

    bs = os.path.join(ASSETS, "blockstates")
    write(os.path.join(bs, "province_core.json"), {"variants": {"": {"model": b + "province_core"}}})
    write(os.path.join(bs, "treasury.json"), {"variants": {"": {"model": b + "treasury"}}})
    write(os.path.join(bs, "steel_block.json"), {"variants": {"": {"model": b + "steel_block"}}})
    write(os.path.join(bs, "construction_site.json"), {"variants": {
        "active=false": {"model": b + "construction_site"},
        "active=true": {"model": b + "construction_site_active"}}})
    variants = {}
    for facing, y in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
        for lit in ("false", "true"):
            v = {"model": b + ("steel_furnace_on" if lit == "true" else "steel_furnace")}
            if y:
                v["y"] = y
            variants["facing=%s,lit=%s" % (facing, lit)] = v
    write(os.path.join(bs, "steel_furnace.json"), {"variants": variants})

    for name in ("province_core", "construction_site", "treasury", "steel_block", "steel_furnace"):
        item_model(name, parent=b + name)
    i = MOD + ":item/"
    for name in ("steel_ingot", "steel_nugget", "steel_helmet", "steel_chestplate", "steel_leggings", "steel_boots"):
        item_model(name, layer=i + name)
    for name in ("steel_sword", "steel_pickaxe", "steel_axe", "steel_shovel"):
        item_model(name, parent="minecraft:item/handheld", layer=i + name)
    for name in ("citizen_spawn_egg", "soldier_spawn_egg"):
        item_model(name, parent="minecraft:item/template_spawn_egg")


# ---------------------------------------------------------------- recipes
def shaped(name, pattern, key, result, count=1):
    k = {}
    for ch, val in key.items():
        k[ch] = {"tag": val[1:]} if val.startswith("#") else {"item": val}
    write(os.path.join(DATA, MOD, "recipes", name + ".json"),
          {"type": "minecraft:crafting_shaped", "category": "misc", "pattern": pattern, "key": k,
           "result": {"item": result, "count": count}})


def shapeless(name, ingredients, result, count=1):
    ing = [{"tag": v[1:]} if v.startswith("#") else {"item": v} for v in ingredients]
    write(os.path.join(DATA, MOD, "recipes", name + ".json"),
          {"type": "minecraft:crafting_shapeless", "category": "misc", "ingredients": ing, "result": {"item": result, "count": count}})


def gen_recipes():
    S = MOD + ":steel_ingot"
    shaped("steel_block", ["SSS", "SSS", "SSS"], {"S": S}, MOD + ":steel_block")
    shapeless("steel_ingot_from_block", [MOD + ":steel_block"], S, 9)
    shaped("steel_ingot_from_nuggets", ["NNN", "NNN", "NNN"], {"N": MOD + ":steel_nugget"}, S)
    shapeless("steel_nugget", [S], MOD + ":steel_nugget", 9)
    stick = "minecraft:stick"
    shaped("steel_sword", [" S ", " S ", " T "], {"S": S, "T": stick}, MOD + ":steel_sword")
    shaped("steel_pickaxe", ["SSS", " T ", " T "], {"S": S, "T": stick}, MOD + ":steel_pickaxe")
    shaped("steel_axe", ["SS ", "ST ", " T "], {"S": S, "T": stick}, MOD + ":steel_axe")
    shaped("steel_shovel", [" S ", " T ", " T "], {"S": S, "T": stick}, MOD + ":steel_shovel")
    shaped("steel_helmet", ["SSS", "S S"], {"S": S}, MOD + ":steel_helmet")
    shaped("steel_chestplate", ["S S", "SSS", "SSS"], {"S": S}, MOD + ":steel_chestplate")
    shaped("steel_leggings", ["SSS", "S S", "S S"], {"S": S}, MOD + ":steel_leggings")
    shaped("steel_boots", ["S S", "S S"], {"S": S}, MOD + ":steel_boots")
    shaped("treasury", ["GGG", "GCG", "III"], {"G": "minecraft:gold_ingot", "C": "minecraft:chest", "I": "minecraft:iron_ingot"}, MOD + ":treasury")
    shaped("steel_furnace", ["III", "IBI", "SSS"], {"I": "minecraft:iron_ingot", "B": "minecraft:blast_furnace", "S": "minecraft:smooth_stone"},
           MOD + ":steel_furnace")


# ---------------------------------------------------------------- loot + tags
def gen_loot():
    for name in ("treasury", "steel_furnace", "steel_block"):
        write(os.path.join(DATA, MOD, "loot_tables", "blocks", name + ".json"), {
            "type": "minecraft:block",
            "pools": [{"rolls": 1, "entries": [{"type": "minecraft:item", "name": MOD + ":" + name}],
                       "conditions": [{"condition": "minecraft:survives_explosion"}]}]})


def tag(path, values):
    write(os.path.join(DATA, path + ".json"), {"replace": False, "values": values})


